const fs = require('node:fs');
const path = require('node:path');
const {chromium} = require('playwright');
const root = path.resolve(__dirname,'..');
const out = path.join(root,'artifacts','qa');
fs.mkdirSync(out,{recursive:true});
const results=[];
const assert=(condition,message)=>{if(!condition)throw new Error(message);};
(async()=>{
 const browser=await chromium.connectOverCDP(process.env.SWAY_CDP_URL||'http://127.0.0.1:9239');
 const page=browser.contexts()[0].pages().find(p=>p.url().startsWith('sway://app/'));
 assert(page,'Native application page must exist');
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.reload({waitUntil:'domcontentloaded',timeout:15000});
 await page.waitForSelector('html[data-ready=true]',{timeout:15000});
 await page.evaluate(()=>document.fonts.ready);
 const about=await page.evaluate(async()=>({native:!!window.desktop,origin:location.origin,tracks:(await(await fetch('/catalog.json')).json()).length}));
 assert(about.native&&about.tracks===7000,'Native bridge and full catalogue');
 results.push({name:'packaged application ready',pass:true,detail:about});
 await page.screenshot({path:path.join(out,'packaged-home-final.png')});
 await page.locator('.nav-main [data-go=search]').click();
 await page.waitForSelector('.search-category');
 assert(await page.locator('.search-category').count()===5,'Five browse categories');
 await page.screenshot({path:path.join(out,'packaged-search-final.png')});
 results.push({name:'reference search overview',pass:true});
 await page.locator('[data-browse=genres]').click();
 assert(await page.locator('.genre-card').count()>0,'Genre list');
 await page.locator('.genre-card').first().click();
 assert(await page.locator('.track-row').count()>0,'Genre actually has catalogue tracks');
 results.push({name:'genre navigation to real catalogue',pass:true});
 await page.locator('.nav-main [data-go=search]').click();
 await page.locator('[data-browse=moods]').click();
 await page.locator('.genre-card').first().click();
 assert(await page.locator('.shelf-hero').count()===1,'Mood shelf');
 results.push({name:'mood shelf navigation',pass:true});
 await page.locator('.nav-main [data-go=search]').click();
 await page.locator('[data-browse=eras]').click();
 assert(await page.locator('.genre-card').count()>0,'Decades derived from catalogue');
 await page.locator('.genre-card').first().click();
 assert(await page.locator('.shelf-hero').count()===1,'Decade shelf');
 results.push({name:'decade shelf navigation',pass:true});
 await page.locator('.nav-main [data-go=collection]').click();
 await page.waitForSelector('.collection-liked');
 await page.screenshot({path:path.join(out,'packaged-collection-final.png')});
 await page.locator('.nav-main [data-go=home]').click();
 await page.evaluate(()=>document.querySelector('audio').pause());
 assert(errors.length===0,'Renderer errors: '+errors.join('; '));
 const report={generatedAt:new Date().toISOString(),results,rendererErrors:errors,passed:results.length,failed:0};
 fs.writeFileSync(path.join(out,'report-packaged-final.json'),JSON.stringify(report,null,2));
 console.log(JSON.stringify(report));
 await browser.close();
})().catch(error=>{fs.writeFileSync(path.join(out,'report-packaged-final.json'),JSON.stringify({results,error:error.message},null,2));console.error(error);process.exitCode=1;});
