"""Create a small UI supplement for legacy bulk-import cover metadata."""
import colorsys
import json
from pathlib import Path
from urllib.parse import unquote
from PIL import Image

root = Path(__file__).resolve().parents[1]
catalog = json.loads((root / 'public/catalog.json').read_text(encoding='utf-8-sig'))
result = {}
missing = []
for track in catalog:
    art = track.get('art') or track.get('cover') or '/art/logo.svg'
    source = root / 'public' / unquote(art).lstrip('/')
    if not source.is_file():
        result[track['id']] = {'art': '/art/logo.svg', 'palette': [220, 9, 28, 227]}
        missing.append(track['id'])
        continue
    if isinstance(track.get('palette'), list):
        continue
    bins = [[0., 0., 0.] for _ in range(24)]
    try:
        with Image.open(source) as image:
            image = image.convert('RGB')
            image.thumbnail((40, 40))
            for r, g, b in image.get_flattened_data():
                hue, light, sat = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
                if light < .12 or light > .93 or sat < .16:
                    continue
                weight = (sat + .2) * (1 - abs(light - .45))
                cell = bins[int(hue * 24) % 24]
                cell[0] += weight
                cell[1] += weight * sat
                cell[2] += weight * light
    except (OSError, ValueError):
        continue
    winner = max(range(24), key=lambda i: bins[i][0])
    count, saturation, light = bins[winner]
    alternate = max(range(24), key=lambda i: bins[i][0] if min((i-winner)%24, (winner-i)%24) >= 2 else 0)
    palette = [round((winner+.5)*15), round(100*saturation/count), round(100*light/count),
               round((alternate+.5)*15) if bins[alternate][0] > count*.2 else round((winner+1.5)*15)%360] if count else [220, 9, 28, 227]
    result[track['id']] = {'palette': palette}
(root / 'public/cover-colors.js').write_text('// Generated by scripts/import-cover-colors.py.\nexport default '+json.dumps(result, ensure_ascii=False, separators=(',', ':'))+';\n', encoding='utf-8')
print(json.dumps({'palettes': len(result), 'fallbackArt': missing}, ensure_ascii=False))
